import { createRequire } from 'node:module';
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const HERE = dirname(fileURLToPath(import.meta.url));
const APP_ROOT = resolve(HERE, '..');
const REPO_ROOT = resolve(APP_ROOT, '..', '..');

export const ICON_DIRECTORY = join(APP_ROOT, 'src', 'renderer', 'public', 'file-icons');

export const MAP_MODULE = join(
	REPO_ROOT,
	'packages',
	'extension-api',
	'src',
	'file-icons',
	'material-icon-map.generated.ts',
);

function packagePaths() {
	const manifestPath = require.resolve('material-icon-theme/dist/material-icons.json');
	const packageJsonPath = require.resolve('material-icon-theme/package.json');
	return {
		manifestPath,
		iconsDirectory: join(dirname(packageJsonPath), 'icons'),
		version: JSON.parse(readFileSync(packageJsonPath, 'utf8')).version,
	};
}

function lowerKeyed(record) {
	return Object.fromEntries(
		Object.entries(record ?? {}).map(([key, id]) => [key.toLowerCase(), id]),
	);
}

function serialize(record) {
	const entries = Object.entries(record)
		.sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
		.map(([key, id]) => `\t${JSON.stringify(key)}: ${JSON.stringify(id)},`);
	return `{\n${entries.join('\n')}\n}`;
}

export function buildFileIconAssets() {
	const { manifestPath, iconsDirectory, version } = packagePaths();
	const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));

	const fileExtensions = lowerKeyed(manifest.fileExtensions);
	const fileNames = lowerKeyed(manifest.fileNames);
	const folderNames = lowerKeyed(manifest.folderNames);
	const folderNamesExpanded = lowerKeyed(manifest.folderNamesExpanded);
	const defaults = {
		file: manifest.file,
		folder: manifest.folder,
		folderExpanded: manifest.folderExpanded,
		rootFolder: manifest.rootFolder,
		rootFolderExpanded: manifest.rootFolderExpanded,
	};

	const referenced = new Set([
		...Object.values(fileExtensions),
		...Object.values(fileNames),
		...Object.values(folderNames),
		...Object.values(folderNamesExpanded),
		...Object.values(defaults),
	]);

	const svgById = new Map();
	const missing = [];
	for (const id of [...referenced].sort()) {
		const iconPath = manifest.iconDefinitions?.[id]?.iconPath;
		const fileName = iconPath ? iconPath.slice(iconPath.lastIndexOf('/') + 1) : `${id}.svg`;
		try {
			svgById.set(id, readFileSync(join(iconsDirectory, fileName), 'utf8').trim());
		} catch {
			missing.push(`${id} (${fileName})`);
		}
	}
	if (missing.length > 0) {
		throw new Error(`material-icon-theme ${version} has no SVG for: ${missing.join(', ')}`);
	}

	const module = [
		'/*',
		' * Generated by scripts/generate-file-icons.mjs from material-icon-theme',
		` * ${version} (MIT). Do not edit; re-run the script instead.`,
		' */',
		'',
		`export const MATERIAL_ICON_THEME_VERSION = ${JSON.stringify(version)};`,
		'',
		`export const FILE_ICON_BY_EXTENSION: Readonly<Record<string, string>> = ${serialize(fileExtensions)};`,
		'',
		`export const FILE_ICON_BY_NAME: Readonly<Record<string, string>> = ${serialize(fileNames)};`,
		'',
		`export const FOLDER_ICON_BY_NAME: Readonly<Record<string, string>> = ${serialize(folderNames)};`,
		'',
		`export const FOLDER_OPEN_ICON_BY_NAME: Readonly<Record<string, string>> = ${serialize(folderNamesExpanded)};`,
		'',
		`export const DEFAULT_FILE_ICON = ${JSON.stringify(defaults.file)};`,
		`export const DEFAULT_FOLDER_ICON = ${JSON.stringify(defaults.folder)};`,
		`export const DEFAULT_FOLDER_OPEN_ICON = ${JSON.stringify(defaults.folderExpanded)};`,
		`export const DEFAULT_ROOT_FOLDER_ICON = ${JSON.stringify(defaults.rootFolder)};`,
		`export const DEFAULT_ROOT_FOLDER_OPEN_ICON = ${JSON.stringify(defaults.rootFolderExpanded)};`,
		'',
	].join('\n');

	return { module, svgById, version, licensePath: join(dirname(manifestPath), '..', 'LICENSE') };
}

export async function formatModule(source, filepath = MAP_MODULE) {
	const prettier = await import('prettier');
	const config = await prettier.resolveConfig(filepath);
	return prettier.format(source, { ...config, filepath });
}

export async function writeFileIconAssets({
	iconDirectory = ICON_DIRECTORY,
	mapModule = MAP_MODULE,
} = {}) {
	const { module, svgById, version, licensePath } = buildFileIconAssets();
	const formatted = await formatModule(module);

	for (const name of readWrittenIconIds(iconDirectory)) {
		rmSync(join(iconDirectory, `${name}.svg`), { force: true });
	}
	mkdirSync(iconDirectory, { recursive: true });
	for (const [id, svg] of svgById) {
		writeFileSync(join(iconDirectory, `${id}.svg`), `${svg}\n`);
	}
	writeFileSync(join(iconDirectory, 'LICENSE'), `${readFileSync(licensePath, 'utf8').trim()}\n`);

	mkdirSync(dirname(mapModule), { recursive: true });
	writeFileSync(mapModule, formatted);

	return { version, iconCount: svgById.size };
}

export function readWrittenIconIds(iconDirectory = ICON_DIRECTORY) {
	try {
		return readdirSync(iconDirectory)
			.filter((name) => name.endsWith('.svg'))
			.map((name) => name.slice(0, -'.svg'.length))
			.sort();
	} catch {
		return [];
	}
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
	const { version, iconCount } = await writeFileIconAssets();
	process.stdout.write(`material-icon-theme ${version}: wrote ${iconCount} icons\n`);
}

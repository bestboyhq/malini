export function ladderDatabase(version: number, stampedVersion = version): MaliniDatabase {
	const db = openDatabase(':memory:');
	for (const [step, statement] of LADDER) {
		if (step <= version) db.exec(statement);
	}
	db.exec(`PRAGMA user_version = ${stampedVersion};`);
	return db;
}
